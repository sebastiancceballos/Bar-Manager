export const messages: Record<Locale, Record<string, string>> = { es, en };

export function translate(
  locale: Locale,
  key: string,
  fallback?: string
): string {
  // Do not cross-fallback between languages (avoids ES text in EN mode and vice versa).
  const table = messages[locale] ?? messages.es;
  return table[key] ?? fallback ?? key;
}
